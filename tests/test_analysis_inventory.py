"""Inventory: language detection, exclusion policy, safe reads, determinism."""

import pytest

from app.analysis.config import AnalysisConfigOverrides, resolve_config
from app.analysis.errors import PathValidationError
from app.analysis.inventory import (
    ExclusionPolicy,
    LanguageDetector,
    RepositoryInspector,
    SourceReader,
)
from app.analysis.registry import build_default_registry


def _write(root, relative: str, content: str):
    path = root / relative
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    return path


@pytest.fixture
def inspector_factory(temp_root):
    registry = build_default_registry()

    def _make(overrides=None):
        config = resolve_config(overrides)
        return RepositoryInspector(temp_root, config, registry), temp_root, config

    return _make


# --- language detection ------------------------------------------------------


def test_python_is_detected_from_the_file_extension(temp_root):
    detector = LanguageDetector()
    assert detector.detect("pkg/module.py") == "python"
    assert detector.detect("stub.pyi") == "python"


def test_a_dot_py_directory_does_not_make_a_file_python(temp_root):
    """`pkg.py/module.txt` is not Python just because `.py` appears in the path."""
    detector = LanguageDetector()
    assert detector.detect("pkg.py/module.txt") is None
    assert detector.detect("deep/module.py/notes.txt") is None


def test_extensionless_file_is_python_only_with_a_python_shebang(temp_root):
    script = _write(temp_root, "bin/tool", "#!/usr/bin/env python3\nprint('hi')\n")
    other = _write(temp_root, "bin/other", "#!/bin/sh\necho hi\n")
    reader = SourceReader(temp_root, max_file_bytes=1024)
    detector = LanguageDetector()

    assert script.exists() and other.exists()
    assert detector.detect("bin/tool", reader=reader) == "python"
    assert detector.detect("bin/other", reader=reader) is None


# --- exclusion policy --------------------------------------------------------


def test_exclusion_policy_marks_dependency_and_build_directories():
    policy = ExclusionPolicy(resolve_config())
    assert policy.check_directory("node_modules").excluded
    assert policy.check_directory(".git").excluded
    assert policy.check_directory(".venv").excluded
    assert policy.check_directory("__pycache__").excluded
    assert policy.check_directory("src").excluded is False


def test_exclusion_policy_never_excludes_the_repository_root(temp_root, inspector_factory):
    inspector, _, _ = inspector_factory()
    _write(temp_root, "app.py", "print('hi')\n")
    report = inspector.inspect()
    assert [entry.path for entry in report.files] == ["app.py"]


def test_exclusion_policy_rejects_binary_minified_lock_and_generated_files(temp_root, inspector_factory):
    inspector, _, _ = inspector_factory()
    _write(temp_root, "app.py", "print('hi')\n")
    _write(temp_root, "stale.pyc", "binary")
    _write(temp_root, "bundle.min.js", "var a=1;")
    _write(temp_root, "package-lock.json", "{}")
    _write(temp_root, "generated.py", "# Code generated by tool. DO NOT EDIT.\nX = 1\n")

    report = inspector.inspect()
    reasons = {entry.path: entry.skip_reason for entry in report.skipped}
    assert [entry.path for entry in report.files] == ["app.py"]
    assert reasons["generated.py"] == "generated_file"
    assert "stale.pyc" in reasons
    assert report.stats.skipped_by_reason.get("generated_file") == 1


def test_project_exclusions_match_paths_and_directory_segments(temp_root, inspector_factory):
    inspector, _, _ = inspector_factory(
        AnalysisConfigOverrides(excluded_paths=["tests", "pkg/**"])
    )
    _write(temp_root, "app.py", "print('hi')\n")
    _write(temp_root, "tests/test_app.py", "print('hi')\n")
    _write(temp_root, "pkg/util.py", "print('hi')\n")

    report = inspector.inspect()
    assert [entry.path for entry in report.files] == ["app.py"]
    # `tests` was pruned as a directory before it was walked; `pkg/**` matched the file.
    assert report.stats.directories_skipped == 1
    assert report.stats.discovered == 2
    assert report.stats.skipped_by_reason == {"excluded_by_project_config": 1}


def test_oversized_file_is_skipped_not_analysed(temp_root, inspector_factory):
    inspector, _, config = inspector_factory()
    _write(temp_root, "small.py", "x = 1\n")
    with open(temp_root / "big.py", "w", encoding="utf-8") as handle:
        handle.write("x = 1\n" * ((config.max_file_bytes // 6) + 10))

    report = inspector.inspect()
    assert [entry.path for entry in report.files] == ["small.py"]
    assert any(entry.skip_reason == "file_too_large" for entry in report.skipped)


def test_enabled_analyzers_narrow_file_applicability(temp_root, inspector_factory):
    inspector, _, _ = inspector_factory(AnalysisConfigOverrides(enabled_analyzers=["ruff"]))
    _write(temp_root, "app.py", "print('hi')\n")

    report = inspector.inspect()
    assert report.files[0].analyzers == ("ruff",)


# --- inventory statistics ----------------------------------------------------


def test_inventory_records_statistics_and_line_counts(temp_root, inspector_factory):
    inspector, _, _ = inspector_factory()
    _write(temp_root, "app.py", "a = 1\nb = 2\n")
    _write(temp_root, "notes.txt", "hello\n")
    _write(temp_root, "node_modules/dep/index.js", "console.log(1)\n")

    report = inspector.inspect()

    assert report.stats.discovered == 2  # node_modules is pruned, never walked
    assert report.stats.analyzed == 1
    assert report.stats.skipped == 1
    assert report.stats.unsupported == 1
    assert report.stats.total_lines == 2
    assert report.languages == ("python",)
    assert report.files[0].line_count == 2
    assert report.files[0].analyzers == ("ruff", "bandit", "radon")


def test_inventory_is_deterministic(temp_root, inspector_factory):
    inspector, _, _ = inspector_factory()
    for name in ("b.py", "a.py", "pkg/c.py"):
        _write(temp_root, name, "x = 1\n")

    first = inspector.inspect()
    second = inspector.inspect()
    assert [entry.path for entry in first.files] == [entry.path for entry in second.files]
    assert [entry.path for entry in first.files] == ["a.py", "b.py", "pkg/c.py"]


def test_file_count_limit_is_enforced(temp_root, inspector_factory):
    inspector, _, config = inspector_factory()
    for index in range(config.max_file_count + 5):
        _write(temp_root, f"mod_{index:04d}.py", "x = 1\n")

    monkeypatched = RepositoryInspector(
        temp_root, resolve_config(), build_default_registry()
    )
    report = monkeypatched.inspect()
    assert report.stats.analyzed == config.max_file_count
    assert report.stats.truncated is True


def test_directory_symlinks_are_not_followed(temp_root, inspector_factory):
    inspector, _, _ = inspector_factory()
    outside = temp_root.parent / "outside_secret"
    outside.mkdir(exist_ok=True)
    (outside / "secret.py").write_text("token = 'x'\n", encoding="utf-8")
    (temp_root / "link").symlink_to(outside, target_is_directory=True)
    _write(temp_root, "app.py", "print('hi')\n")

    report = inspector.inspect()
    assert [entry.path for entry in report.files] == ["app.py"]
    assert report.stats.symlinks_skipped == 1


def test_file_symlinks_are_skipped(temp_root, inspector_factory):
    inspector, _, _ = inspector_factory()
    (temp_root / "target.py").write_text("x = 1\n", encoding="utf-8")
    (temp_root / "link.py").symlink_to(temp_root / "target.py")

    report = inspector.inspect()
    assert [entry.path for entry in report.files] == ["target.py"]
    assert any(entry.skip_reason == "symlink" for entry in report.skipped)


# --- safe reads --------------------------------------------------------------


@pytest.mark.parametrize("candidate", ["../secret.txt", "/etc/passwd", "a/../../b.py", "", "C:\\windows\\x.py"])
def test_source_reader_refuses_unsafe_paths(temp_root, candidate):
    reader = SourceReader(temp_root, max_file_bytes=1024)
    with pytest.raises(PathValidationError):
        reader.resolve(candidate)


def test_source_reader_refuses_oversized_files(temp_root):
    _write(temp_root, "big.py", "x" * 4096)
    reader = SourceReader(temp_root, max_file_bytes=128)
    with pytest.raises(PathValidationError):
        reader.resolve("big.py")


def test_source_reader_reports_binary_content(temp_root):
    (temp_root / "blob.py").write_bytes(b"bin\x00ary\n")
    reader = SourceReader(temp_root, max_file_bytes=1024)
    lines, is_binary = reader.count_lines("blob.py")
    assert (lines, is_binary) == (None, True)


def test_source_reader_refuses_symlink_escapes(temp_root):
    outside = temp_root.parent / "outside.txt"
    outside.write_text("secret\n", encoding="utf-8")
    (temp_root / "link.py").symlink_to(outside)
    reader = SourceReader(temp_root, max_file_bytes=1024)
    with pytest.raises(PathValidationError):
        reader.resolve("link.py")
