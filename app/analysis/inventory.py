"""Repository inventory: discovery, language detection, exclusions, safe reads.

Deterministic by construction (sorted walk, sorted results) so the same archive
always yields the same file list, metrics and fingerprints.

The exclusion policy is centralised here and split in two:

* **mandatory** rules (VCS metadata, non-regular files, control characters in a
  name, over-long paths) that a project can never turn off;
* **default** rules (dependency and build directories, caches, binary and
  minified files, lock files, generated files, oversized files) that apply to
  every run and that a project can only *add* to through
  `excluded_paths` — a project cannot un-exclude `node_modules`.

Every skipped file is recorded with a reason, so a run's summary can explain
what was analysed and what was not.
"""

import os
import re
import stat
from dataclasses import dataclass, field
from pathlib import Path
from typing import Iterator, Optional

from app.analysis.config import AnalysisConfig
from app.analysis.errors import PathValidationError
from app.analysis.observability import log_event
from app.analysis.paths import MAX_PATH_CHARS, is_within, lexical_relative_path, normalize_relative_path
from app.analysis.registry import AnalyzerRegistry

_CHUNK = 64 * 1024
_MAX_SAMPLE_BYTES = 4096
_SURROGATE_RANGE = range(0xDC80, 0xDD00)

# --- language detection ------------------------------------------------------

EXTENSION_LANGUAGE: dict[str, str] = {
    ".py": "python",
    ".pyi": "python",
    ".pyw": "python",
    ".py3": "python",
}

# Extensionless files are resolved by their interpreter shebang instead: see
# `LanguageDetector.detect`.
_SHEBANG = re.compile(rb"^#!.*\bpython[0-9.]*\b", re.IGNORECASE)


class LanguageDetector:
    """Detects the language of a file from its *basename*, then its shebang.

    Detection is deliberately conservative: an extension on a directory name
    (`pkg.py/module.txt`) never makes a file Python, and content sniffing is
    limited to the interpreter shebang of an extensionless file — guessing from
    file contents produces false positives that a project cannot debug.
    """

    def detect(self, relative_path: str, *, reader: "SourceReader | None" = None) -> Optional[str]:
        name = relative_path.rsplit("/", 1)[-1]
        dot = name.rfind(".")
        if dot > 0:
            return EXTENSION_LANGUAGE.get(name[dot:].lower())
        if reader is not None:
            head = reader.read_bytes(relative_path, limit=128, missing_ok=True)
            if head and _SHEBANG.match(head):
                return "python"
        return None


# --- exclusion policy --------------------------------------------------------

MANDATORY_DIRECTORY_NAMES = frozenset({".git", ".hg", ".svn", ".bzr", "__macosx"})
DEFAULT_DIRECTORY_NAMES = frozenset(
    {
        "node_modules", "bower_components", "vendor", "venv", ".venv", "env", ".env",
        "virtualenv", "site-packages", "__pycache__", ".mypy_cache", ".ruff_cache",
        ".pytest_cache", ".tox", ".nox", ".eggs", "build", "dist", "target",
        "htmlcov", ".idea", ".vscode", ".next", ".nuxt", ".cache", ".gradle",
        ".terraform", ".serverless", "coverage", "tests_cache",
    }
)
BINARY_EXTENSIONS = frozenset(
    {
        ".pyc", ".pyo", ".pyd", ".so", ".dylib", ".dll", ".exe", ".bin", ".o", ".a",
        ".class", ".jar", ".war", ".ear", ".wasm", ".zip", ".tar", ".gz", ".tgz",
        ".bz2", ".xz", ".7z", ".rar", ".png", ".jpg", ".jpeg", ".gif", ".webp",
        ".ico", ".pdf", ".woff", ".woff2", ".ttf", ".otf", ".eot", ".mp3", ".mp4",
        ".mov", ".avi", ".sqlite", ".db", ".mo", ".egg", ".whl", ".pickle", ".pkl",
        ".npy", ".npz", ".pt", ".onnx", ".dat",
    }
)
MINIFIED_SUFFIXES = (".min.js", ".min.css", ".min.mjs")
LOCKFILE_NAMES = frozenset(
    {
        "package-lock.json", "yarn.lock", "pnpm-lock.yaml", "poetry.lock",
        "pipfile.lock", "gemfile.lock", "composer.lock", "cargo.lock",
        "go.sum", "packages.lock.json", ".ds_store",
    }
)
GENERATED_MARKERS = (
    "code generated",
    "do not edit",
    "@generated",
    "automatically generated",
    "autogenerated",
    "generated by",
)


@dataclass(frozen=True)
class ExclusionDecision:
    excluded: bool
    reason: Optional[str] = None


class ExclusionPolicy:
    """Centralised, deterministic exclusion policy for one run."""

    def __init__(self, config: AnalysisConfig):
        self._config = config
        self._project_patterns = tuple(config.excluded_paths)

    # --- directories -------------------------------------------------------

    def check_directory(self, name: str) -> ExclusionDecision:
        lowered = name.lower()
        if lowered in MANDATORY_DIRECTORY_NAMES:
            return ExclusionDecision(True, "version_control_metadata")
        if lowered in DEFAULT_DIRECTORY_NAMES:
            return ExclusionDecision(True, "dependency_or_build_directory")
        if self._matches_project_pattern(name):
            return ExclusionDecision(True, "excluded_by_project_config")
        return ExclusionDecision(False)

    # --- files -------------------------------------------------------------

    def check_file(
        self,
        relative_path: str,
        *,
        size_bytes: int,
        sample: Optional[str] = None,
        is_binary: bool = False,
    ) -> ExclusionDecision:
        name = relative_path.rsplit("/", 1)[-1].lower()
        if len(relative_path) > MAX_PATH_CHARS:
            return ExclusionDecision(True, "path_too_long")
        if any(_SURROGATE_RANGE.start <= ord(char) < _SURROGATE_RANGE.stop for char in relative_path):
            return ExclusionDecision(True, "invalid_filename_encoding")
        if "\x00" in relative_path:
            return ExclusionDecision(True, "control_characters_in_name")

        extension = name[name.rfind("."):] if "." in name else ""
        if extension in BINARY_EXTENSIONS:
            return ExclusionDecision(True, "binary_file")
        if is_binary:
            return ExclusionDecision(True, "binary_content")
        if name.endswith(MINIFIED_SUFFIXES):
            return ExclusionDecision(True, "minified_file")
        if name in LOCKFILE_NAMES:
            return ExclusionDecision(True, "lock_file")
        if size_bytes > self._config.max_file_bytes:
            return ExclusionDecision(True, "file_too_large")
        if sample and self._looks_generated(sample):
            return ExclusionDecision(True, "generated_file")
        if self._matches_project_pattern(relative_path):
            return ExclusionDecision(True, "excluded_by_project_config")
        if name.endswith(".dist-info") or "-dist-info" in relative_path.lower():
            return ExclusionDecision(True, "packaging_metadata")
        return ExclusionDecision(False)

    # --- internals ---------------------------------------------------------

    @staticmethod
    def _looks_generated(sample: str) -> bool:
        head = sample[:2000].lower()
        return any(marker in head for marker in GENERATED_MARKERS)

    def _matches_project_pattern(self, relative_path: str) -> bool:
        """Match a project pattern against the whole path *or* one segment.

        Segment matching is what makes `excluded_paths: ["tests"]` behave the way
        a user expects without a `**/tests/**` incantation.
        """
        import fnmatch

        if not self._project_patterns:
            return False
        normalized = relative_path.replace("\\", "/")
        segments = normalized.split("/")
        for pattern in self._project_patterns:
            if fnmatch.fnmatch(normalized, pattern):
                return True
            if any(fnmatch.fnmatch(segment, pattern) for segment in segments):
                return True
        return False


# --- safe reads --------------------------------------------------------------


class SourceReader:
    """Reads files inside the workspace only, with hard size caps."""

    def __init__(self, root: Path, *, max_file_bytes: int):
        self._root = root
        self._max_file_bytes = max_file_bytes

    def resolve(self, relative_path: str) -> Path:
        """Absolute path of a workspace file, rejecting anything suspicious."""
        normalized = normalize_relative_path(self._root, relative_path)
        if normalized is None:
            raise PathValidationError(f"Refusing to read an unsafe path: {relative_path!r}")
        candidate = self._root / normalized
        if candidate.is_symlink():
            raise PathValidationError(f"Refusing to follow a symlink: {normalized}")
        if not is_within(self._root, candidate):
            raise PathValidationError(f"Path escapes the workspace: {normalized}")
        try:
            info = candidate.stat()
        except OSError as exc:
            raise PathValidationError(f"Could not stat {normalized}: {exc.strerror or 'unknown'}") from exc
        if not stat.S_ISREG(info.st_mode):
            raise PathValidationError(f"Not a regular file: {normalized}")
        if info.st_size > self._max_file_bytes:
            raise PathValidationError(f"File exceeds the size limit: {normalized}")
        return candidate

    def read_bytes(self, relative_path: str, *, limit: int, missing_ok: bool = False) -> bytes:
        try:
            path = self.resolve(relative_path)
        except PathValidationError:
            if missing_ok:
                return b""
            raise
        with open(path, "rb") as handle:
            return handle.read(limit)

    def read_head(self, relative_path: str, *, limit: int = _MAX_SAMPLE_BYTES) -> tuple[str, bool]:
        """Return `(decoded sample, is_binary)` without reading the whole file."""
        path = self.resolve(relative_path)
        with open(path, "rb") as handle:
            chunk = handle.read(min(limit, self._max_file_bytes))
        is_binary = b"\x00" in chunk
        return chunk.decode("utf-8", "replace"), is_binary

    def count_lines(self, relative_path: str) -> tuple[Optional[int], bool]:
        """`(line count, is_binary)`; `None` when the file is not text.

        Counting is streaming and capped at `max_file_bytes`, so a 1MB file of
        1MB-long lines costs one pass and no memory growth.
        """
        path = self.resolve(relative_path)
        lines = 0
        try:
            with open(path, "rb") as handle:
                first = True
                while True:
                    chunk = handle.read(_CHUNK)
                    if not chunk:
                        break
                    if first:
                        first = False
                        if b"\x00" in chunk:
                            return None, True
                    lines += chunk.count(b"\n")
                if lines == 0 and path.stat().st_size > 0:
                    lines = 1
        except OSError:
            return None, False
        return lines, False


# --- inventory ---------------------------------------------------------------


@dataclass(frozen=True)
class FileEntry:
    """One inventory entry (analysed candidate or skipped file)."""

    path: str
    language: Optional[str]
    extension: str
    size_bytes: int
    line_count: Optional[int]
    analyzers: tuple[str, ...]
    skipped: bool = False
    skip_reason: Optional[str] = None


@dataclass
class InventoryStats:
    directories: int = 0
    directories_skipped: int = 0
    symlinks_skipped: int = 0
    discovered: int = 0
    analyzed: int = 0
    skipped: int = 0
    unsupported: int = 0
    failed: int = 0
    total_bytes: int = 0
    total_lines: int = 0
    truncated: bool = False
    skipped_by_reason: dict[str, int] = field(default_factory=dict)

    def record_skip(self, reason: Optional[str]) -> None:
        key = reason or "unknown"
        self.skipped_by_reason[key] = self.skipped_by_reason.get(key, 0) + 1


@dataclass
class InventoryReport:
    root: Path
    files: tuple[FileEntry, ...]
    skipped: tuple[FileEntry, ...]
    failures: tuple[tuple[str, str], ...]
    stats: InventoryStats
    languages: tuple[str, ...]

    def paths_for(self, analyzer: str) -> tuple[str, ...]:
        return tuple(entry.path for entry in self.files if analyzer in entry.analyzers)


class RepositoryInspector:
    """Walks a snapshot once and produces the deterministic file inventory."""

    _MAX_FAILURES_RECORDED = 20

    def __init__(self, root: Path, config: AnalysisConfig, registry: AnalyzerRegistry):
        self._root = root
        self._config = config
        self._registry = registry
        self._policy = ExclusionPolicy(config)
        self._detector = LanguageDetector()
        self._reader = SourceReader(root, max_file_bytes=config.max_file_bytes)

    def inspect(self) -> InventoryReport:
        stats = InventoryStats()
        analyzed: list[FileEntry] = []
        skipped: list[FileEntry] = []
        failures: list[tuple[str, str]] = []
        languages: set[str] = set()

        for current, dirnames, filenames in self._walk():
            stats.directories += 1
            # `dirnames` is what os.walk descends into: removing an entry here
            # prunes the whole subtree (iterating over a copy keeps that safe).
            for dirname in list(dirnames):
                decision = self._policy.check_directory(dirname)
                path = Path(current) / dirname
                if decision.excluded:
                    dirnames.remove(dirname)
                    stats.directories_skipped += 1
                    continue
                if path.is_symlink():
                    dirnames.remove(dirname)
                    stats.symlinks_skipped += 1

            for filename in filenames:
                relative = lexical_relative_path(self._root, os.path.join(current, filename))
                if relative is None:
                    stats.discovered += 1
                    stats.skipped += 1
                    stats.record_skip("invalid_path")
                    continue
                stats.discovered += 1
                entry, failure = self._inspect_file(relative)
                if failure is not None:
                    stats.failed += 1
                    if len(failures) < self._MAX_FAILURES_RECORDED:
                        failures.append((relative, failure))
                    continue
                if entry is None:  # pragma: no cover - defensive
                    continue
                if entry.skipped:
                    skipped.append(entry)
                    stats.skipped += 1
                    stats.record_skip(entry.skip_reason)
                    if entry.skip_reason == "unsupported_language":
                        stats.unsupported += 1
                    continue
                analyzed.append(entry)
                stats.analyzed += 1
                stats.total_bytes += entry.size_bytes
                stats.total_lines += entry.line_count or 0
                if entry.language:
                    languages.add(entry.language)
                if stats.analyzed >= self._config.max_file_count:
                    stats.truncated = True
                    log_event(
                        "inventory_file_limit_reached",
                        level=30,
                        limit=self._config.max_file_count,
                    )
                    break
            if stats.truncated:
                break

        return InventoryReport(
            root=self._root,
            files=tuple(sorted(analyzed, key=lambda entry: entry.path)),
            skipped=tuple(sorted(skipped, key=lambda entry: entry.path)),
            failures=tuple(failures),
            stats=stats,
            languages=tuple(sorted(languages)),
        )

    # --- internals ---------------------------------------------------------

    def _walk(self) -> Iterator[tuple[str, list[str], list[str]]]:
        for current, dirnames, filenames in os.walk(self._root, followlinks=False):
            dirnames.sort()
            filenames.sort()
            yield current, dirnames, filenames

    def _inspect_file(self, relative: str) -> tuple[Optional[FileEntry], Optional[str]]:
        path = self._root / relative
        if path.is_symlink():
            return FileEntry(relative, None, _extension(relative), 0, None, (), True, "symlink"), None
        try:
            info = path.stat()
        except OSError as exc:
            return None, f"stat_failed:{(exc.strerror or 'unknown').replace(' ', '_')}"
        if not stat.S_ISREG(info.st_mode):
            return FileEntry(relative, None, _extension(relative), 0, None, (), True, "not_a_regular_file"), None

        if info.st_size > self._config.max_file_bytes:
            # Checked before anything opens the file: reading it just to reject it
            # would waste the very budget the limit exists to protect.
            return (
                FileEntry(relative, None, _extension(relative), info.st_size, None, (), True, "file_too_large"),
                None,
            )

        language = self._detector.detect(relative, reader=self._reader)
        analyzers = (
            self._registry.applicable(language, enabled=self._config.enabled_analyzers)
            if language
            else ()
        )

        sample: Optional[str] = None
        is_binary = False
        if not analyzers:
            if language is None:
                return (
                    FileEntry(relative, None, _extension(relative), info.st_size, None, (), True, "unsupported_language"),
                    None,
                )
            return (
                FileEntry(relative, language, _extension(relative), info.st_size, None, (), True, "no_applicable_analyzer"),
                None,
            )

        try:
            sample, is_binary = self._reader.read_head(relative)
        except PathValidationError as exc:
            return None, f"unreadable:{type(exc).__name__}"

        decision = self._policy.check_file(
            relative, size_bytes=info.st_size, sample=sample, is_binary=is_binary
        )
        if decision.excluded:
            return (
                FileEntry(
                    relative,
                    language,
                    _extension(relative),
                    info.st_size,
                    None,
                    (),
                    True,
                    decision.reason,
                ),
                None,
            )

        try:
            line_count, binary_content = self._reader.count_lines(relative)
        except PathValidationError as exc:
            return None, f"unreadable:{type(exc).__name__}"
        if binary_content:
            return (
                FileEntry(relative, language, _extension(relative), info.st_size, None, (), True, "binary_content"),
                None,
            )

        return (
            FileEntry(
                path=relative,
                language=language,
                extension=_extension(relative),
                size_bytes=info.st_size,
                line_count=line_count,
                analyzers=analyzers,
            ),
            None,
        )


def _extension(relative: str) -> str:
    name = relative.rsplit("/", 1)[-1]
    dot = name.rfind(".")
    return name[dot:].lower() if dot > 0 else ""
